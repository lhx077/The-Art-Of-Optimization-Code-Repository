// ============================================================================
// DiRegistrationGenerator — Incremental Source Generator
// ============================================================================
// Discovers classes annotated with [Service(ServiceLifetime.X)] and emits a
// static registration method that calls AddSingleton/AddScoped/AddTransient
// on IServiceCollection, eliminating runtime assembly scanning.
// ============================================================================

#nullable enable

using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace DiGenerator;

[Generator]
public sealed class DiRegistrationIncrementalGenerator : IIncrementalGenerator
{
    private const string AttributeSource = """
        // <auto-generated />
        public enum ServiceLifetime { Singleton, Scoped, Transient }

        [System.AttributeUsage(System.AttributeTargets.Class, Inherited = false)]
        public sealed class ServiceAttribute : System.Attribute
        {
            public ServiceAttribute(ServiceLifetime lifetime) => Lifetime = lifetime;
            public ServiceLifetime Lifetime { get; }
        }
        """;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(ctx =>
            ctx.AddSource("ServiceAttribute.g.cs", AttributeSource));

        var services = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                "ServiceAttribute",
                predicate: static (node, _) => node is ClassDeclarationSyntax,
                transform: static (ctx, _) => GetDescriptor(ctx))
            .Where(static d => d is not null)
            .Select(static (d, _) => d!.Value);

        var collected = services.Collect();

        context.RegisterSourceOutput(collected, static (spc, descriptors) =>
        {
            string source = EmitRegistration(descriptors);
            spc.AddSource("GeneratedServiceRegistration.g.cs", source);
        });
    }

    private static ServiceDescriptor? GetDescriptor(GeneratorAttributeSyntaxContext ctx)
    {
        if (ctx.TargetSymbol is not INamedTypeSymbol typeSymbol)
            return null;

        var attr = ctx.Attributes.FirstOrDefault();
        if (attr is null || attr.ConstructorArguments.Length == 0)
            return null;

        int lifetimeValue = (int)attr.ConstructorArguments[0].Value!;

        string implType = typeSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        string serviceType = typeSymbol.Interfaces.Length > 0
            ? typeSymbol.Interfaces[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
            : implType;

        return new ServiceDescriptor(serviceType, implType, lifetimeValue);
    }

    private static string EmitRegistration(ImmutableArray<ServiceDescriptor> descriptors)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        sb.AppendLine();
        sb.AppendLine("public static class GeneratedServiceRegistration");
        sb.AppendLine("{");
        sb.AppendLine("    public static IServiceCollection AddGeneratedServices(this IServiceCollection services)");
        sb.AppendLine("    {");

        foreach (var svc in descriptors)
        {
            string method = svc.Lifetime switch
            {
                0 => "AddSingleton",
                1 => "AddScoped",
                _ => "AddTransient"
            };
            sb.Append("        services.").Append(method).Append('<')
              .Append(svc.ServiceType).Append(", ").Append(svc.ImplementationType)
              .AppendLine(">();");
        }

        sb.AppendLine("        return services;");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private readonly struct ServiceDescriptor
    {
        public ServiceDescriptor(string serviceType, string implementationType, int lifetime)
        { ServiceType = serviceType; ImplementationType = implementationType; Lifetime = lifetime; }
        public string ServiceType { get; }
        public string ImplementationType { get; }
        public int Lifetime { get; }
    }
}
