// ============================================================================
// AutoNotifyGenerator — Incremental Source Generator
// ============================================================================
// Discovers classes annotated with [AutoNotify], finds private _fields, and
// emits public properties with INotifyPropertyChanged change notification.
// ============================================================================

#nullable enable

using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace AutoNotifyGenerator;

[Generator]
public sealed class AutoNotifyIncrementalGenerator : IIncrementalGenerator
{
    private const string AttributeSource = """
        // <auto-generated />
        [System.AttributeUsage(System.AttributeTargets.Class, Inherited = false)]
        internal sealed class AutoNotifyAttribute : System.Attribute { }
        """;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(ctx =>
            ctx.AddSource("AutoNotifyAttribute.g.cs", AttributeSource));

        var pipeline = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                "AutoNotifyAttribute",
                predicate: static (node, _) => node is ClassDeclarationSyntax,
                transform: static (ctx, _) => GetDescriptor(ctx))
            .Where(static d => d is not null)
            .Select(static (d, _) => d!.Value);

        context.RegisterSourceOutput(pipeline, static (spc, descriptor) =>
        {
            string source = EmitSource(descriptor);
            spc.AddSource($"{descriptor.TypeName}.g.cs", source);
        });
    }

    private static TypeDescriptor? GetDescriptor(GeneratorAttributeSyntaxContext ctx)
    {
        if (ctx.TargetSymbol is not INamedTypeSymbol typeSymbol)
            return null;

        var fields = new List<FieldDescriptor>();
        foreach (var member in typeSymbol.GetMembers())
        {
            if (member is not IFieldSymbol field) continue;
            if (field.IsStatic || field.DeclaredAccessibility != Accessibility.Private) continue;
            if (field.Name.Length < 2 || field.Name[0] != '_') continue;

            string propName = char.ToUpperInvariant(field.Name[1]) + field.Name.Substring(2);
            fields.Add(new FieldDescriptor(
                field.Name,
                propName,
                field.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)));
        }

        if (fields.Count == 0) return null;

        bool baseHasInpc = typeSymbol.BaseType is not null &&
            typeSymbol.BaseType.AllInterfaces.Any(static i =>
                i.Name == "INotifyPropertyChanged" &&
                i.ContainingNamespace?.ToDisplayString() == "System.ComponentModel");

        string ns = typeSymbol.ContainingNamespace.IsGlobalNamespace
            ? string.Empty
            : typeSymbol.ContainingNamespace.ToDisplayString();

        return new TypeDescriptor(ns, typeSymbol.Name, baseHasInpc, fields.ToArray());
    }

    private static string EmitSource(TypeDescriptor type)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("using System.ComponentModel;");
        sb.AppendLine();

        if (!string.IsNullOrEmpty(type.Namespace))
        {
            sb.Append("namespace ").Append(type.Namespace).AppendLine(";");
            sb.AppendLine();
        }

        sb.Append("partial class ").AppendLine(type.TypeName);
        sb.AppendLine("{");

        foreach (var field in type.Fields)
        {
            sb.Append("    public ").Append(field.TypeName).Append(' ').AppendLine(field.PropertyName);
            sb.AppendLine("    {");
            sb.Append("        get => ").Append(field.FieldName).AppendLine(";");
            sb.AppendLine("        set");
            sb.AppendLine("        {");
            sb.Append("            if (").Append(field.FieldName).AppendLine(" == value) return;");
            sb.Append("            ").Append(field.FieldName).AppendLine(" = value;");
            string notifier = type.BaseHasInpc ? "RaisePropertyChanged" : "OnPropertyChanged";
            sb.Append("            ").Append(notifier).Append("(nameof(").Append(field.PropertyName).AppendLine("));");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private readonly struct TypeDescriptor
    {
        public TypeDescriptor(string ns, string typeName, bool baseHasInpc, FieldDescriptor[] fields)
        { Namespace = ns; TypeName = typeName; BaseHasInpc = baseHasInpc; Fields = fields; }
        public string Namespace { get; }
        public string TypeName { get; }
        public bool BaseHasInpc { get; }
        public FieldDescriptor[] Fields { get; }
    }

    private readonly struct FieldDescriptor
    {
        public FieldDescriptor(string fieldName, string propertyName, string typeName)
        { FieldName = fieldName; PropertyName = propertyName; TypeName = typeName; }
        public string FieldName { get; }
        public string PropertyName { get; }
        public string TypeName { get; }
    }
}
